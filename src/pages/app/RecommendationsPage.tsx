import React, { useState } from 'react';
import { Target, AlertTriangle, Megaphone, BarChart3, CheckCircle2, Sparkles } from 'lucide-react';
import { AppLayout } from '../../components/layout/AppLayout';
import { Button } from '../../components/ui/Button';
import { StatusBadge } from '../../components/ui/StatusBadge';
import { useApp } from '../../context/AppContext';

export const RecommendationsPage: React.FC = () => {
  const { recommendations, applyRecommendation } = useApp();
  const [selectedCat, setSelectedCat] = useState<string>('ALL');

  const filtered = recommendations.filter((r) => {
    if (selectedCat === 'ALL') return true;
    return r.category === selectedCat;
  });

  const getIcon = (type: string) => {
    switch (type) {
      case 'target':
        return <Target className="w-5 h-5 text-[#0f7654]" />;
      case 'alert':
        return <AlertTriangle className="w-5 h-5 text-[#dc2626]" />;
      case 'megaphone':
        return <Megaphone className="w-5 h-5 text-[#059669]" />;
      case 'chart':
      default:
        return <BarChart3 className="w-5 h-5 text-[#2563eb]" />;
    }
  };

  return (
    <AppLayout
      title="AI Recommendations"
      subtitle="Data-driven prescriptive actions generated by machine learning models to maximize portfolio yield and mitigate risk."
    >
      <div className="flex items-center justify-between flex-wrap gap-3 mb-6">
        <div className="flex items-center gap-1 p-1 bg-white border border-[#e5dfd2] rounded-xl text-xs">
          {(['ALL', 'Growth', 'Risk Prevention', 'Engagement', 'Credit'] as const).map((cat) => (
            <button
              key={cat}
              onClick={() => setSelectedCat(cat)}
              className={`px-3 py-1.5 rounded-lg font-medium transition-colors ${
                selectedCat === cat
                  ? 'bg-[#0b3829] text-white shadow-2xs font-semibold'
                  : 'text-slate-600 hover:text-black'
              }`}
            >
              {cat}
            </button>
          ))}
        </div>

        <span className="text-xs text-slate-500 font-medium">
          Confidence threshold: &gt;85% required for automated suggestion
        </span>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {filtered.map((rec) => (
          <div
            key={rec.recommendation_id}
            className="bg-white border border-[#ece7dc] rounded-2xl p-5 shadow-xs flex flex-col justify-between hover:shadow-md transition-all"
          >
            <div>
              <div className="flex items-center justify-between mb-3">
                <div className="flex items-center gap-2.5">
                  <div className="p-2.5 rounded-xl bg-[#faf7f0] border border-[#f0ece1]">
                    {getIcon(rec.icon_type)}
                  </div>
                  <div>
                    <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400">
                      {rec.category}
                    </span>
                    <h3 className="font-heading font-semibold text-sm text-[#092b1e]">
                      {rec.title}
                    </h3>
                  </div>
                </div>
                <StatusBadge status={rec.status} />
              </div>

              <p className="text-xs text-slate-600 leading-relaxed mt-2 mb-4">
                {rec.description}
              </p>

              <div className="flex items-center gap-4 text-xs text-slate-500 py-2 border-t border-[#f5f2ea]">
                <div>
                  Model Confidence: <strong className="text-[#0d5941]">{rec.confidence}%</strong>
                </div>
                <div>·</div>
                <div>Priority: <strong className="text-slate-800">{rec.priority}</strong></div>
              </div>
            </div>

            <div className="mt-4 pt-3 border-t border-[#f5f2ea] flex items-center justify-between">
              <span className="text-[11px] text-slate-400">Human-reviewable recommendation</span>
              <Button
                variant={rec.status === 'Applied' ? 'primary' : 'emerald'}
                size="sm"
                disabled={rec.status === 'Applied'}
                onClick={() => applyRecommendation(rec.recommendation_id)}
                leftIcon={rec.status === 'Applied' ? <CheckCircle2 className="w-3.5 h-3.5" /> : <Sparkles className="w-3.5 h-3.5 text-[#f1cd6b]" />}
              >
                {rec.status === 'Applied' ? 'Action Applied' : rec.action_label}
              </Button>
            </div>
          </div>
        ))}
      </div>
    </AppLayout>
  );
};
